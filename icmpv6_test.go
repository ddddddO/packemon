package packemon

import (
	"bytes"
	"testing"
)

func TestParsedPacket_icmpv6RouterSolicitation(t *testing.T) {
	// Router Solicitation（ヘッダ 8 バイト + Source Link-Layer Address オプション 8 バイト）
	sourceLinkLayerAddressOption := []byte{0x01, 0x01, 0x02, 0x11, 0x22, 0x33, 0x44, 0x55}
	rs := append([]byte{0x85, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}, sourceLinkLayerAddressOption...)

	ipv6 := []byte{
		0x60, 0x00, 0x00, 0x00, 0x00, byte(len(rs)), IPv6_NEXT_HEADER_ICMPv6, 0xff,
		0xfe, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
		0xff, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02,
	}
	frame := NewEthernetFrame(
		HardwareAddr{0x33, 0x33, 0x00, 0x00, 0x00, 0x02},
		HardwareAddr{0x02, 0x11, 0x22, 0x33, 0x44, 0x55},
		ETHER_TYPE_IPv6,
		append(ipv6, rs...),
	)

	passive := ParsedPacket(frame.Bytes(), true)
	if passive.ICMPv6RouterSolicitation == nil {
		t.Fatal("router solicitation should be parsed")
	}
	if got := passive.ICMPv6RouterSolicitation.Options; !bytes.Equal(got, sourceLinkLayerAddressOption) {
		t.Fatalf("options = %x, want %x", got, sourceLinkLayerAddressOption)
	}
}
